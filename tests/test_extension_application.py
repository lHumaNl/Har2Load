"""Target code is opaque data; contracts never authorize execution at preparation."""

import hashlib
import json
from pathlib import Path

import pytest

from har2load.application import Application
from har2load.cli import main
from har2load.domain import Har2LoadError
from har2load.serialization import canonical_bytes


def setup(tmp_path):
    source = tmp_path / "source.har"
    source.write_text(json.dumps({"log": {"entries": [{
        "comment": "Use token", "request": {
            "method": "GET", "url": "https://example.invalid/?token=recorded",
        }, "response": {"status": 200, "content": {"mimeType": "text/plain", "text": "ok"}},
    }]}}))
    app, workspace = Application(), tmp_path / "w"
    app.import_capture(source, workspace)
    entity = app.summary(workspace)["data"]["entries"][0]["id"]
    return app, workspace, entity


def block(entity, target="jmeter"):
    return {
        "id": "code_" + target, "behavior_id": "make_token", "target": target,
        "language": "groovy" if target == "jmeter" else "c",
        "source": "// PRIVATE_SYNTHETIC_SOURCE\n/* unexecuted */\n",
        "placement": {"event": "before_request", "exchange_id": entity},
        "order": 10, "depends_on": [], "inputs": [], "outputs": ["token"],
        "helper_calls": [], "dependencies": [], "side_effects": ["unknown"],
        "failure_policy": "mark_error_and_continue",
        "failed_input_policy": "skip_and_mark_outputs", "reset_outputs": True,
        "purpose": "Author declares token formation; not verified by preparation",
    }


def operations(entity, targets=("jmeter", "loadrunner")):
    return [{"op": "upsert_variable", "variable": {
        "id": "token", "name": "token", "value_type": "string",
        "source": {"kind": "agent_code", "behavior_id": "make_token"},
        "initialize": {"event": "before_request", "exchange_id": entity},
        "scope": "iteration", "reset": "iteration_start",
        "purpose": "Token generated by explicitly authored target code", "sensitive": True,
    }}, {"op": "upsert_binding", "binding": {
        "id": "use", "variable_id": "token", "exchange_id": entity,
        "location": {"area": "request_query", "index": 0},
    }}, *[{"op": "upsert_code_block", "block": block(entity, target)} for target in targets]]


def changes(tmp_path, entity, ops, *, base=1, identifier="extensions"):
    path = tmp_path / f"{identifier}.json"
    path.write_text(json.dumps({
        "schema_version": "1.0", "change_id": identifier, "base_revision": base,
        "author": "synthetic-agent", "rationale": "Explicit opaque code with declared contracts",
        "evidence": [{"exchange_id": entity, "location": "/request"}], "operations": ops,
    }))
    return path


def tree(workspace):
    return {p.name: p.read_bytes() for p in workspace.iterdir()}


def test_code_contract_batch_is_audited_but_never_executed(tmp_path, monkeypatch, capsys):
    app, workspace, entity = setup(tmp_path)
    source = changes(tmp_path, entity, operations(entity))
    before = tree(workspace)

    def forbidden(*args, **kwargs):
        raise AssertionError("Native execution forbidden")

    with monkeypatch.context() as patch:
        patch.setattr("socket.socket", forbidden)
        patch.setattr("subprocess.Popen", forbidden)
        patch.setattr("os.getenv", forbidden)
        assert app.changes_validate(workspace, source)["data"]["proposed_revision"] == 2
        assert tree(workspace) == before
        app.changes_apply(workspace, source)
        assert main(["validate", "--workspace", str(workspace)]) == 0
        result = json.loads(capsys.readouterr().out)
        assert result["data"]["code_block_count"] == 2
        assert result["data"]["target_contracts"] == {"jmeter": "valid", "loadrunner": "valid"}
        assert result["data"]["code_semantics"] == "unverified"
        assert "PRIVATE_SYNTHETIC_SOURCE" not in json.dumps(result)
    inspected = json.loads(app.inspect(workspace, section="code-blocks")["data"]["content"])
    assert len(inspected) == 2
    digest = hashlib.sha256(block(entity)["source"].encode()).hexdigest()
    assert inspected[0]["source_digest"] == digest
    assert app.changes_apply(workspace, source)["data"]["replayed"] is True
    assert app.summary(workspace, revision=1)["data"]["code_block_count"] == 0


def test_missing_counterpart_blocks_only_that_target_not_storage_or_reports(tmp_path, capsys):
    app, workspace, entity = setup(tmp_path)
    app.changes_apply(workspace, changes(tmp_path, entity, operations(entity, ("jmeter",))))
    assert main(["validate", "--workspace", str(workspace)]) == 3
    result = json.loads(capsys.readouterr().out)
    assert result["data"]["target_contracts"] == {"jmeter": "valid", "loadrunner": "blocked"}
    assert any(d["code"] == "TARGET_IMPLEMENTATION_MISSING" and d["target"] == "loadrunner"
               for d in result["diagnostics"])
    destination = tmp_path / "report"
    app.report(workspace, output=destination)
    report = json.loads((destination / "report.json").read_bytes())
    assert report["targets"]["loadrunner"]["status"] == "blocked"
    assert report["targets"]["jmeter"]["status"] == "not_generated"
    assert report["target_extensions"]["model"]["blocks"][0]["source"] == block(entity)["source"]
    assert report["variables"][0]["formation"]["code_blocks"][0]["id"] == "code_jmeter"
    assert report["diff"]["blocks"]["added"] == ["code_jmeter"]
    assert any(row["kind"] == "code_block" and row["status"] == "not_generated"
               for row in report["source_map"])
    assert report["statuses"]["code_semantics"] == "unverified"


def test_previous_scalar_scenario_requires_explicit_audited_extension_upgrade(tmp_path):
    app, workspace, entity = setup(tmp_path)
    scenario_path, manifest_path = workspace / "scenario.json", workspace / "manifest.json"
    scenario = json.loads(scenario_path.read_bytes())
    scenario["schema_version"] = "1.2"
    scenario.pop("target_extensions", None)
    encoded = canonical_bytes(scenario)
    scenario_path.write_bytes(encoded)
    manifest = json.loads(manifest_path.read_bytes())
    manifest["producer_version"] = "0.4.0a1"
    digest = hashlib.sha256(encoded).hexdigest()
    manifest["scenario_sha256"] = manifest["initial_scenario_sha256"] = digest
    manifest_path.write_bytes(canonical_bytes(manifest))
    before = tree(workspace)
    assert app.summary(workspace)["data"]["code_block_count"] == 0
    with pytest.raises(Har2LoadError):
        app.changes_apply(workspace, changes(tmp_path, entity, operations(entity)))
    assert tree(workspace) == before
    upgrade = changes(tmp_path, entity, [{"op": "upgrade_extensions"}, *operations(entity)],
                      identifier="upgrade")
    app.changes_apply(workspace, upgrade)
    old = json.loads(app.inspect(workspace, section="scenario", revision=1)["data"]["content"])
    assert old["schema_version"] == "1.2" and "target_extensions" not in old
    assert app.validate(workspace)["data"]["target_contracts"]["jmeter"] == "valid"


def test_dangling_code_output_removal_rolls_back_whole_batch(tmp_path):
    app, workspace, entity = setup(tmp_path)
    app.changes_apply(workspace, changes(tmp_path, entity, operations(entity)))
    before = tree(workspace)
    remove = changes(tmp_path, entity, [{"op": "remove_code_block", "id": "code_jmeter"},
                                      {"op": "remove_code_block", "id": "code_loadrunner"}],
                     base=2, identifier="remove")
    with pytest.raises(Har2LoadError):
        app.changes_apply(workspace, remove)
    assert tree(workspace) == before


def test_code_changes_invalidate_report_identity_and_preserve_history(tmp_path):
    app, workspace, entity = setup(tmp_path)
    app.changes_apply(workspace, changes(tmp_path, entity, operations(entity)))
    before = app.report(workspace)["data"]["report_sha256"]
    edited = {**block(entity), "source": "// changed opaque implementation\n"}
    source = changes(tmp_path, entity, [{"op": "upsert_code_block", "block": edited}],
                     base=2, identifier="edit")
    app.changes_apply(workspace, source)
    assert app.report(workspace)["data"]["report_sha256"] != before
    assert app.report(workspace, revision=2)["data"]["report_sha256"] == before


def helper():
    return {"id": "helper_jm", "target": "jmeter", "language": "groovy",
            "source": "// OPAQUE_HELPER\n", "namespace": "scenario_helpers", "symbol": "normalize",
            "parameters": [{"name": "value", "value_type": "string"}], "return_type": "string",
            "depends_on": [], "dependencies": [{"kind": "jar", "path": "lib/not-present.jar"}],
            "side_effects": [], "stateless": True, "thread_safe": True,
            "purpose": "Declared helper, actual body and thread safety unverified"}


def test_helpers_dependencies_call_sites_and_removed_calls_are_reported(tmp_path):
    app, workspace, entity = setup(tmp_path)
    ops = operations(entity)
    ops[2]["block"]["helper_calls"] = ["helper_jm"]
    ops.append({"op": "upsert_helper", "helper": helper()})
    app.changes_apply(workspace, changes(tmp_path, entity, ops))
    result = app.validate(workspace)
    assert result["data"]["declared_dependency_count"] == 1
    assert result["data"]["runtime_inputs"] == "required_at_runtime"
    plan = json.loads(app.inspect(workspace, section="extension-plan")["data"]["content"])
    assert plan["targets"]["jmeter"]["helpers"][0]["id"] == "helper_jm"
    app.report(workspace, output=tmp_path / "report")
    report = json.loads((tmp_path / "report" / "report.json").read_bytes())
    assert report["runtime_dependencies"][0]["resolution"] == "required_at_runtime"
    assert any(row["kind"] == "helper_call" and row["helper_id"] == "helper_jm"
               for row in report["source_map"])
    app.changes_apply(workspace, changes(tmp_path, entity, [
        {"op": "upsert_code_block", "block": block(entity)},
    ], base=2, identifier="remove-call"))
    app.report(workspace, output=tmp_path / "report2")
    changed = json.loads((tmp_path / "report2" / "report.json").read_bytes())
    assert any(row["kind"] == "helper_call" and row["disposition"] == "removed"
               for row in changed["source_map"])
    assert any(row["kind"] == "helper_definition" and row["disposition"] == "unused"
               for row in changed["source_map"])


