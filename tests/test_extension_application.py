def test_two_explicit_upgrades_from_schema_11_share_one_audited_revision(tmp_path):
    app, workspace, entity = setup(tmp_path)
    scenario_path, manifest_path = workspace / "scenario.json", workspace / "manifest.json"
    scenario = json.loads(scenario_path.read_bytes())
    scenario["schema_version"] = "1.1"
    del scenario["target_extensions"], scenario["parameters"]
    encoded = canonical_bytes(scenario)
    scenario_path.write_bytes(encoded)
    manifest = json.loads(manifest_path.read_bytes())
    manifest["producer_version"] = "0.2.0a1"
    digest = hashlib.sha256(encoded).hexdigest()
    manifest["scenario_sha256"] = manifest["initial_scenario_sha256"] = digest
    manifest_path.write_bytes(canonical_bytes(manifest))
    before = tree(workspace)
    with pytest.raises(Har2LoadError):
        app.changes_apply(workspace, changes(tmp_path, entity, [{"op": "upgrade_extensions"}]))
    assert tree(workspace) == before
    source = changes(tmp_path, entity, [{"op": "upgrade_parameters"}, {"op": "upgrade_extensions"},
                                       *operations(entity)], identifier="two-upgrades")
    app.changes_apply(workspace, source)
    current = app.store.load(workspace)
    assert current.scenario_revision == 2 and current.scenario["schema_version"] == "1.3"
    assert len(current.history) == 1
    assert (workspace / "scenario.json").read_bytes() == encoded
    historical = app.store.load(workspace, 1).scenario
    assert historical["schema_version"] == "1.1" and "parameters" not in historical


def test_retargeted_block_helper_and_calls_keep_removed_target_dispositions(tmp_path):
    app, workspace, entity = setup(tmp_path)
    original_block = {**block(entity), "outputs": [], "helper_calls": ["helper_jm"]}
    original_helper = {**helper(), "dependencies": []}
    app.changes_apply(workspace, changes(tmp_path, entity, [
        {"op": "upsert_code_block", "block": original_block},
        {"op": "upsert_helper", "helper": original_helper},
    ]))
    app.changes_apply(workspace, changes(tmp_path, entity, [
        {"op": "upsert_code_block", "block": {**original_block, "target": "loadrunner",
                                               "language": "c"}},
        {"op": "upsert_helper", "helper": {**original_helper, "target": "loadrunner",
                                           "language": "c"}},
    ], base=2, identifier="retarget"))
    app.report(workspace, output=tmp_path / "report")
    report = json.loads((tmp_path / "report" / "report.json").read_bytes())
    for kind in ("code_block", "helper_definition", "helper_call", "reset_outputs"):
        assert any(row["kind"] == kind and row["target"] == "jmeter"
                   and row["disposition"] == "removed" for row in report["source_map"])
        assert any(row["kind"] == kind and row["target"] == "loadrunner"
                   and row["disposition"] == "declared" for row in report["source_map"])
    assert report["diff"]["blocks"]["changed"] == ["code_jmeter"]
    assert report["diff"]["blocks"]["removed"] == []


